import { readFileSync, writeFileSync } from "node:fs";
import { projectOffense, scoreDst, scoreOffense } from "../src/lib/fantasy/scoring";
import { environmentFrom } from "../src/lib/fantasy/brain/environment";
import { DEFAULT_WEIGHTS } from "../src/lib/fantasy/brain/weights";
import type { CountStats, DstStats, Pos } from "../src/lib/fantasy/types";

interface PackRow {
  playerId: string;
  name: string;
  pos: Pos;
  week: number;
  team: string;
  opp: string;
  home: boolean;
  spread: number | null;
  total: number | null;
  stats: CountStats;
  prior: { games: number; targetShare: number; carryShare: number; snap: number | null; pace: number; passRate: number } | null;
  priorWeeks: number;
}

interface DstRow {
  playerId: string;
  week: number;
  stats: DstStats;
}

const pack = JSON.parse(readFileSync("/tmp/nfl/pack.json", "utf8")) as {
  rows: PackRow[];
  dst: DstRow[];
  slate: Record<string, Record<string, { opp: string; home: boolean; spread: number | null; total: number | null; bye: boolean }>>;
  fullyScoredWeeks: number[];
};

const actualByPlayer = new Map<string, Map<number, number>>();

function remember(id: string, week: number, points: number) {
  const map = actualByPlayer.get(id) ?? new Map<number, number>();
  map.set(week, points);
  actualByPlayer.set(id, map);
}

const replayRows: { playerId: string; week: number; actual: number; brain: number | null; baseline: number | null; baselineWeeks: number }[] = [];

for (const row of pack.rows) {
  const actual = scoreOffense(row.stats);
  remember(row.playerId, row.week, actual);
  let brain: number | null = null;
  if (row.prior && row.prior.games >= 1 && row.pos !== "DST") {
    const env = environmentFrom(
      { spread: row.spread, total: row.total, pace: row.prior.pace, wind: null },
      DEFAULT_WEIGHTS,
    );
    const snap = row.prior.snap ?? 0.55;
    const projected = projectOffense({
      pos: row.pos as "QB" | "RB" | "WR" | "TE",
      plays: env.pace,
      passRate: env.passRate,
      rushRate: env.rushRate,
      qbShare: row.pos === "QB" ? 0.98 : 1,
      carryShare: row.pos === "QB" ? Math.min(0.2, row.prior.carryShare) : row.prior.carryShare,
      targetShare: row.pos === "QB" ? 0 : row.prior.targetShare,
      snap,
      ypc: row.pos === "QB" ? 5.2 : 4.3,
      ypt: row.pos === "TE" ? 7.2 : row.pos === "RB" ? 6.4 : row.pos === "QB" ? 7.3 : 8.4,
      tdPerRush: 0.045,
      tdPerTarget: 0.05,
      cmp: 0.65,
      sackRate: 0.07,
      explosive: row.prior.targetShare > 0.2 ? 0.2 : 0.08,
      wind: 0,
      rain: false,
      windPassCut: DEFAULT_WEIGHTS.windPassCut,
      efficiencyRegress: DEFAULT_WEIGHTS.efficiencyRegress,
    });
    brain = scoreOffense(projected);
  }
  const prev = [...(actualByPlayer.get(row.playerId)?.entries() ?? [])].filter(([w]) => w < row.week).sort((a, b) => b[0] - a[0]).slice(0, 3);
  const baselineWeeks = prev.length;
  const baseline = baselineWeeks === 3 ? prev.reduce((s, [, p]) => s + p, 0) / 3 : null;
  if (row.week <= 4) {
    replayRows.push({
      playerId: row.playerId,
      week: row.week,
      actual: Math.round(actual * 10) / 10,
      brain: brain == null ? null : Math.round(brain * 10) / 10,
      baseline: baseline == null ? null : Math.round(baseline * 10) / 10,
      baselineWeeks,
    });
  }
}

for (const row of pack.dst) {
  remember(row.playerId, row.week, scoreDst(row.stats));
}

const trailing: Record<string, number> = {};
for (const [id, weeks] of actualByPlayer) {
  const last3 = [1, 2, 3].filter((w) => weeks.has(w)).map((w) => weeks.get(w)!);
  if (last3.length === 3) trailing[id] = Math.round((last3.reduce((s, n) => s + n, 0) / 3) * 10) / 10;
}

const comparable = replayRows.filter((r) => r.baselineWeeks >= 3 && r.brain != null && r.baseline != null);
const brainMae = comparable.reduce((s, r) => s + Math.abs(r.actual - (r.brain ?? 0)), 0) / Math.max(1, comparable.length);
const baselineMae = comparable.reduce((s, r) => s + Math.abs(r.actual - (r.baseline ?? 0)), 0) / Math.max(1, comparable.length);

const record = {
  source: "nflverse",
  origin: "job",
  season: 2026,
  completedWeeks: pack.fullyScoredWeeks.length,
  comparableWeeks: [...new Set(comparable.map((r) => r.week))],
  brainMae: Math.round(brainMae * 100) / 100,
  baselineMae: Math.round(baselineMae * 100) / 100,
  rows: comparable,
};

writeFileSync("src/lib/fantasy/brain/stored/replay.ts", `/* Generated by scripts/write-brain-store.ts from nflverse 2026. Not a handwritten fixture. */\nexport const REPLAY_RECORD = ${JSON.stringify(record, null, 2)} as const;\n`);
writeFileSync("src/lib/fantasy/brain/stored/baseline.ts", `/* Trailing three scored weeks (1-3). Players without all three are omitted. */\nexport const TRAILING: Record<string, number> = ${JSON.stringify(trailing)};\n`);
writeFileSync("src/lib/fantasy/brain/stored/slate.ts", `export interface SlateWeek { opp: string; home: boolean; spread: number | null; total: number | null; bye: boolean }\nexport const SLATE: Record<string, Record<string, SlateWeek>> = ${JSON.stringify(pack.slate)};\n`);
writeFileSync("src/lib/fantasy/brain/stored/grades.ts", `import type { CorrectionRow, GradeRow } from "../types";\nexport const GRADE_ROWS: GradeRow[] = [];\nexport const CORRECTIONS: CorrectionRow[] = [];\n`);
writeFileSync("src/lib/fantasy/brain/stored/freezes.ts", `import type { FreezeMeta } from "../types";\nexport const FREEZE_ROWS: FreezeMeta[] = [];\n`);

